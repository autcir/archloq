#!/usr/bin/env bash
# =============================================================================
# 01 — kernel, LUKS keyfile, systemd-boot, resume
# =============================================================================
# archinstall has already installed the kernel, laid out the partitions and
# installed systemd-boot. This script does what archinstall could not:
#
#  * generate the initramfs keyfile and register it in /etc/crypttab
#  * fix the fstab that `genfstab -U` produced for our explicit subvolumes
#  * install the systemd-boot kernel-install config
#  * verify Secure Boot really is off
#  * wire up hibernate (opt-in)
#
# systemd-boot cannot prompt for a LUKS passphrase, so the only place one can
# appear is the initramfs. We embed a keyfile and keep the passphrase valid in
# slot 0 as the recovery path. See docs/RECOVERY.md.
# =============================================================================

set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/utils.sh
source "$SCRIPT_DIR/../lib/utils.sh"

require_root
require_config
init_dirs

KEYFILE_DIR="/etc/cryptsetup-keys.d"
KEYFILE="$KEYFILE_DIR/loq-root.key"
ROOT_LUKS="$LOQ_ROOT_PARTITION"
SWAP_LUKS="$LOQ_SWAP_PARTITION"

# -----------------------------------------------------------------------------
say "== 01 kernel and boot =="

# -----------------------------------------------------------------------------
# Secure Boot must be off: we ship unsigned kernel images, no sbctl.
# -----------------------------------------------------------------------------
secure_boot_enabled() {
  local f
  for f in /sys/firmware/efi/efivars/SecureBoot-*; do
    [[ -r "$f" ]] || continue
    # The variable is 4 bytes little-endian; the last byte holds the state.
    if [[ "$(tail -c 1 "$f" 2>/dev/null | od -An -tu1 | tr -d ' \n')" == "1" ]]; then
      return 0
    fi
  done
  return 1
}

if secure_boot_enabled; then
  die "Secure Boot is enabled. Disable it in the firmware setup: we ship unsigned kernels and no sbctl."
fi
ok "Secure Boot is disabled"

# -----------------------------------------------------------------------------
# mkinitcpio hooks. archinstall's custom_commands already set these, but a
# profile edited by hand may not have run them.
# -----------------------------------------------------------------------------
# mkinitcpio hooks. On LUKS+btrfs (archinstall wipe) these must include
# systemd+sd-encrypt+btrfs. On the current studioloq ext4+GRUB install they
# must NOT: block+filesystems+fsck is correct there.
if cryptsetup isLuks "$LOQ_ROOT_PARTITION" 2>/dev/null; then
  if ! grep -q 'sd-encrypt' /etc/mkinitcpio.conf; then
    note "mkinitcpio has no sd-encrypt hook; adding it (LUKS root detected)"
    sed_idempotent /etc/mkinitcpio.conf \
      's/^HOOKS=.*/HOOKS=(base udev autodetect microcode modconf kms keyboard keymap consolefont systemd sd-encrypt btrfs filesystems fsck)/' \
      "added sd-encrypt + btrfs to mkinitcpio HOOKS"
  fi
else
  skip "ext4 root detected; leaving mkinitcpio HOOKS without sd-encrypt"
fi
# NOTE: sd-encrypt is a mkinitcpio hook, not a pacman package. Do not pkg_install it.

mkdir -p /etc/mkinitcpio.conf.d
write_file /etc/mkinitcpio.conf.d/nvidia.conf 0644 <<'EOF'
# The NVIDIA modules must be in the initramfs: the early userspace needs the GPU
# for the display manager's mode setting, and for suspend/resume.
install_modules+=" nvidia nvidia_drm nvidia_modeset nvidia_uvm "
EOF

# -----------------------------------------------------------------------------
# LUKS keyfile
# -----------------------------------------------------------------------------
if cryptsetup isLuks "$ROOT_LUKS" 2>/dev/null; then
  mkdir -p "$KEYFILE_DIR"
  chmod 0700 "$KEYFILE_DIR"

  if [[ ! -f "$KEYFILE" ]]; then
    say "generating a new LUKS keyfile"
    dd if=/dev/urandom of="$KEYFILE" bs=512 count=8 status=none
    chmod 0400 "$KEYFILE"
    chown root:root "$KEYFILE"

    root_uuid="$(luks_uuid "$ROOT_LUKS")"
    swap_uuid=""
    [[ -n "${SWAP_LUKS:-}" ]] && swap_uuid="$(luks_uuid "$SWAP_LUKS")"
    [[ -n "$root_uuid" ]] || die "could not read a LUKS UUID from $ROOT_LUKS"

    say "adding the keyfile to slot 1 of every encrypted partition"
    cryptsetup luksAddKey "$ROOT_LUKS" "$KEYFILE"
    if [[ -n "$swap_uuid" && -n "${SWAP_LUKS:-}" ]]; then
      cryptsetup luksAddKey "$SWAP_LUKS" "$KEYFILE"
    fi
    ok "keyfile registered"
  else
    skip "keyfile already exists at $KEYFILE"
  fi

  root_uuid="$(luks_uuid "$ROOT_LUKS")"
  swap_uuid=""
  [[ -n "${SWAP_LUKS:-}" ]] && swap_uuid="$(luks_uuid "$SWAP_LUKS")"

  # -----------------------------------------------------------------------------
  # crypttab
  # -----------------------------------------------------------------------------
  {
    printf '# Generated by archloq 01_kernel_boot.sh -- do not hand-edit.\n'
    printf '# Slot 0 keeps the human passphrase as the recovery path.\n'
    printf 'root UUID=%s %s none luks,initramfs\n' "$root_uuid" "$KEYFILE"
    if [[ -n "$swap_uuid" ]]; then
      printf 'swap UUID=%s %s none luks,initramfs,nofail\n' "$swap_uuid" "$KEYFILE"
    fi
  } | write_file /etc/crypttab 0400
else
  skip "root $ROOT_LUKS is not LUKS (ext4 install); skipping keyfile + crypttab"
  root_uuid=""
  swap_uuid=""
fi

# -----------------------------------------------------------------------------
# fstab
#
# `genfstab -U` writes `subvolid=256,subvol=/@` for our root. A hard-coded
# subvolid breaks snapshot rollback, because a rolled-back root is a different
# subvolume with a different id. Strip the subvolid and keep the name.
# -----------------------------------------------------------------------------
if grep -qE 'subvolid=' /etc/fstab; then
  say "stripping hard-coded subvolid from /etc/fstab"
  sed -i 's/,subvolid=[0-9]*//g; s/,subvol=\/@/,subvol=@/g' /etc/fstab
  ok "fstab now uses subvol=@ by name"
fi

# noatime belongs on every btrfs mount; genfstab will not add it.
if ! grep -q 'noatime' /etc/fstab; then
  note "adding noatime to the btrfs mounts in /etc/fstab"
  sed -i 's|,compress=zstd\(,ssd\)\{0,1\}|,compress=zstd,noatime,ssd,space_cache=v2|g' /etc/fstab
fi
grep -q 'space_cache=v2' /etc/fstab || sed -i 's|,compress=zstd|noatime,ssd,space_cache=v2,compress=zstd|' /etc/fstab
ok "btrfs mount options normalised"

# The external backup disk is mounted by UUID from /etc/fstab itself, not
# by udisks2 and not from /etc/fstab.d (systemd-fstab-generator only reads
# /etc/fstab), so backups do not depend on a desktop session being open.
if ! grep -qE '^UUID=.*[[:space:]]'"$LOQ_BACKUP_MOUNT"'[[:space:]]' /etc/fstab; then
  backup_uuid=""
  backup_uuid="$(blkid -s UUID -o value "LABEL=$LOQ_BACKUP_LABEL" 2>/dev/null || true)"
  if [[ -n "$backup_uuid" ]]; then
    printf 'UUID=%s %s ext4 defaults,noatime,nodev,nosuid 0 2\n' "$backup_uuid" "$LOQ_BACKUP_MOUNT" >>/etc/fstab
    ok "added $LOQ_BACKUP_MOUNT to /etc/fstab"
    mkdir -p "$LOQ_BACKUP_MOUNT"
  else
    warn "no filesystem with label $LOQ_BACKUP_LABEL found; skipping its fstab entry"
  fi
fi

# -----------------------------------------------------------------------------
# systemd-boot (wipe installs only). studioloq boots via GRUB+UKI, so never
# install systemd-boot alongside it: two loaders on one ESP fight.
# -----------------------------------------------------------------------------
if pacman -Qq grub >/dev/null 2>&1 || [[ -d /boot/grub ]]; then
  skip "GRUB detected; leaving the bootloader alone (no systemd-boot install)"
else
  write_file /boot/loader/loader.conf 0644 <<EOF
# archloq. Regenerated by 01_kernel_boot.sh.
default arch-*
timeout $LOQ_BOOT_TIMEOUT
console-mode max
editor no
random-seed off
EOF
  ok "wrote /boot/loader/loader.conf"

# Kernel entries come from the kernel-install plugin that ships with
# systemd's 90-loaderentry.install, plus this drop-in so entries are named
# "arch-*" and keep our quiet/rd.luks defaults.
write_file /etc/kernel/cmdline.d/20-archloq.conf 0644 <<'EOF'
quiet
loglevel=3
rd.luks.options=timeout=0
EOF

if [[ ! -f /etc/kernel/install.conf.d/60-archloq.conf ]]; then
  mkdir -p /etc/kernel/install.conf.d
  write_file /etc/kernel/cmdline 0644 <<'EOF'
quiet loglevel=3 rd.luks.options=timeout=0
EOF
  ok "wrote /etc/kernel/cmdline"
else
  skip "kernel cmdline already configured"
fi

pkg_install systemd efibootmgr

# systemd-boot must be installed into the ESP we actually created, and the
# firmware must be told to boot it. Only done when the ESP is mounted.
if findmnt -no FSTYPE /boot | grep -qi 'vfat'; then
  run bootctl install --esp-path=/boot --no-variables 2>/dev/null \
    || run bootctl --esp-path=/boot install 2>/dev/null \
    || warn "bootctl install failed; check ESP layout manually"
  ok "systemd-boot installed to the ESP"
else
  warn "/boot is not a mounted vfat filesystem; skipping bootctl install"
fi
fi # end wipe-only systemd-boot block

# -----------------------------------------------------------------------------
# hibernate (opt-in)
# -----------------------------------------------------------------------------
if enabled "${LOQ_ENABLE_HIBERNATE:-0}"; then
  if [[ -z "$swap_uuid" ]]; then
    warn "hibernate requested but $SWAP_LUKS is not a LUKS container"
  else
    say "enabling hibernate"
    systemctl enable systemd-hibernate-resume.service 2>/dev/null || true

    # With a swap partition the resume target is the opened mapper, so the
    # kernel parameter references its UUID, not the raw partition's.
    resume_uuid=""
    if [[ -b /dev/mapper/swap ]]; then
      resume_uuid="$(blkid -s UUID -o value /dev/mapper/swap 2>/dev/null || true)"
    fi
    if [[ -n "$resume_uuid" ]]; then
      printf 'quiet loglevel=3 rd.luks.options=timeout=0 resume=UUID=%s\n' "$resume_uuid" \
        | write_file /etc/kernel/cmdline 0644
      ok "resume=UUID=$resume_uuid written to /etc/kernel/cmdline"
    else
      warn "swap is not open right now; run 'loq-activate-hibernate' after first boot to finish this"
    fi
  fi
else
  skip "hibernate disabled (LOQ_ENABLE_HIBERNATE=0); suspend works, resume is not set up"
fi

# -----------------------------------------------------------------------------
say "regenerating initramfs images"
run mkinitcpio -P
ok "initramfs regenerated"

run systemctl enable systemd-zram-setup@zram0.service 2>/dev/null || true

summary_line "01: kernel $LOQ_KERNEL, systemd-boot, LUKS keyfile in initramfs"
marker_set 01_kernel_boot
ok "01 kernel and boot complete"